export function chapterById(id: string): TextbookChapter | undefined {
  return TEXTBOOK_CHAPTERS.find((chapter) => chapter.id === id);
}

export function chapterNumber(id: string): number {
  return TEXTBOOK_CHAPTERS.findIndex((chapter) => chapter.id === id) + 1;
}

/** 前後の章（章末の順路ナビ用）。 */
export function chapterNeighbors(id: string): {
  prev: TextbookChapter | null;
  next: TextbookChapter | null;
} {
  const index = TEXTBOOK_CHAPTERS.findIndex((chapter) => chapter.id === id);
  return {
    prev: index > 0 ? TEXTBOOK_CHAPTERS[index - 1] : null,
    next: index >= 0 && index < TEXTBOOK_CHAPTERS.length - 1 ? TEXTBOOK_CHAPTERS[index + 1] : null,
  };
}

export function chapterPath(id: string): string {
  return `/textbook/${id}`;
}
